// Attribution integrity — the tamper-resistant layer under Discord presence.
//
// Same shape and the same honest ceiling as feeIntegrity.ts: this runs on the
// user's machine, so a debugger beats it. What it defeats is the casual crack
// — open the packaged app, grep for the Discord client id or the krypt.cc
// button, and edit it out so the build advertises nothing (or advertises
// somebody else).
//
// The identity is carried here as an obfuscated blob plus a SHA-256 of the
// packed record. The presence path resolves THROUGH this module, which:
//
//   1. decodes the canonical identity from the blob,
//   2. checks it against its own checksum (blob not corrupted),
//   3. compares it to the readable PRESENCE constants,
//   4. returns the CANONICAL identity regardless — so editing the readable
//      constants in a cracked build changes a decoy and publishes nothing
//      different.
//
// A different keystream from feeIntegrity.ts on purpose: finding one blob
// must not hand over the other.
//
// Regenerate after changing shared/presence.ts with:
//   node scripts/gen-presence-integrity.mjs

import { sha256Hex } from './hash';
import { PRESENCE, packIdentity, unpackIdentity, type PresenceIdentity } from './presence';

// Encoded canonical identity (see header). Regenerated by the script above —
// do NOT hand-edit; the checksum below must match.
const TABLE: number[] = [
  6, 230, 185, 176, 163, 207, 107, 89, 10, 183, 210, 236, 19, 190, 8, 154, 242, 235, 122, 247, 222, 160,
  49, 140, 238, 197, 7, 215, 137, 117, 90, 194, 143, 14, 60, 215, 248, 174, 142, 171, 158, 10, 82, 202,
  226, 250, 30, 210, 159, 84, 150, 0, 251, 178, 228, 173, 211, 226, 28, 147, 36, 234, 114, 98, 171, 183,
  242, 255, 189, 104, 64, 23, 166, 154, 52, 239, 252, 83, 67, 156, 160, 160, 55, 249, 62, 225, 155, 93,
  184, 122, 57, 234, 111, 30, 89, 175, 153, 171, 9, 94, 10, 220, 191, 71, 242, 74, 81, 241, 71, 20,
  118, 202, 1, 254, 35, 93, 144, 78, 52, 89, 54, 165, 186, 128, 197, 49, 95, 188, 105, 216, 16, 200,
  119, 247, 36, 216, 16, 183, 19, 54, 118, 93, 153, 135, 3, 137, 224, 187, 103, 212, 133, 226,
];
const TABLE_SHA256 = '9151e22fbffbaf20c3368df7492eb71b1172c36a4bd1743e8e53ca72936c001c';

// Keystream parameters. Named as if they were table geometry so a grep for
// "key" or "secret" turns up nothing.
const ROWS = 1664525;
const COLS = 1013904223;
const SPAN = 2 ** 32;
const ORIGIN = 0x6b727970;

function decodeCanonical(): string {
  let s = ORIGIN;
  let out = '';
  for (let i = 0; i < TABLE.length; i++) {
    s = (Math.imul(ROWS, s) + COLS) % SPAN;
    const k = (s >>> 11) & 0xff;
    out += String.fromCharCode(TABLE[i] ^ k);
  }
  return out;
}

export type PresenceIntegrityState = 'ok' | 'identity-tampered' | 'blob-corrupt';

export interface PresenceIntegrityResult {
  /** The identity presence MUST publish. Always the canonical one, or null
   *  when the blob itself cannot be trusted. */
  identity: PresenceIdentity | null;
  state: PresenceIntegrityState;
  /** True only when the readable constants, the blob and the checksum agree. */
  intact: boolean;
}

/**
 * Resolve the presence identity through the integrity layer.
 *
 * The returned identity is ALWAYS the canonical decoded one — callers must
 * use it rather than the readable PRESENCE constants, so that editing those
 * in a cracked build cannot change what Discord shows.
 */
export function resolvePresence(readable: PresenceIdentity = PRESENCE): PresenceIntegrityResult {
  const packed = decodeCanonical();

  // The blob is corrupt, or was re-encoded without fixing the checksum.
  if (sha256Hex(packed) !== TABLE_SHA256) {
    // Fail CLOSED for presence: no verified identity means publish nothing,
    // which is better than publishing someone else's. Never blocks the app.
    return { identity: null, state: 'blob-corrupt', intact: false };
  }

  const canonical = unpackIdentity(packed);
  if (!canonical) return { identity: null, state: 'blob-corrupt', intact: false };

  if (packIdentity(readable) !== packed) {
    // The readable constants were edited. The canonical still wins.
    return { identity: canonical, state: 'identity-tampered', intact: false };
  }

  return { identity: canonical, state: 'ok', intact: true };
}

/** Canonical identity, no comparison — for places that just need the truth. */
export function canonicalPresence(): PresenceIdentity | null {
  const packed = decodeCanonical();
  if (sha256Hex(packed) !== TABLE_SHA256) return null;
  return unpackIdentity(packed);
}
